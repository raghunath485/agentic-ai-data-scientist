    @staticmethod
    def package_microservice_zip(
        fastapi_code: str,
        dockerfile_code: str,
        docker_compose_code: str,
        joblib_bytes: Optional[bytes] = None
    ) -> bytes:
        """Creates an in-memory ZIP package ready for deployment."""
        zip_buffer = io.BytesIO()
        with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zip_file:
            zip_file.writestr("main.py", fastapi_code)
            zip_file.writestr("Dockerfile", dockerfile_code)
            zip_file.writestr("docker-compose.yml", docker_compose_code)
            zip_file.writestr("requirements.txt", "fastapi>=0.100.0\nuvicorn>=0.22.0\nscikit-learn>=1.4.0\npandas>=2.0.0\njoblib>=1.3.0\n")
            if joblib_bytes:
                zip_file.writestr("best_pipeline.joblib", joblib_bytes)

        return zip_buffer.getvalue()
